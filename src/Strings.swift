// UI translations: one block per language. build.sh checks that every language has every key
// with the same format specifiers as Russian (tests/check_strings.swift).
import Foundation

enum Lang: String, CaseIterable {
    case az, be, de, en, es, fr, he, hy, it, ja, ka, kk, ko, ky, pt, ro, ru, tg, tk, tr, uk, uz, zh

    var nativeName: String {
        switch self {
        case .az: return "Azərbaycanca"
        case .be: return "Беларуская"
        case .de: return "Deutsch"
        case .en: return "English"
        case .es: return "Español"
        case .fr: return "Français"
        case .he: return "עברית"
        case .hy: return "Հայերեն"
        case .it: return "Italiano"
        case .ja: return "日本語"
        case .ka: return "ქართული"
        case .kk: return "Қазақ тілі"
        case .ko: return "한국어"
        case .ky: return "Кыргызча"
        case .pt: return "Português"
        case .ro: return "Română"
        case .ru: return "Русский"
        case .tg: return "Тоҷикӣ"
        case .tk: return "Türkmençe"
        case .tr: return "Türkçe"
        case .uk: return "Українська"
        case .uz: return "Oʻzbekcha"
        case .zh: return "中文（简体）"
        }
    }

    // Menu order: alphabetical by native name with a fixed collation (Latin, then Cyrillic, then other
    // scripts), so the order does not depend on the system language.
    static let sorted: [Lang] = {
        let root = Locale(identifier: "en")
        return allCases.sorted { $0.nativeName.compare($1.nativeName, options: .caseInsensitive, range: nil, locale: root) == .orderedAscending }
    }()

    var isRTL: Bool { self == .he }

    // nil in settings means "follow the system language"; unsupported system languages fall back to English.
    static var chosen: Lang? {
        get { UserDefaults.standard.string(forKey: "language").flatMap(Lang.init(rawValue:)) }
        set { UserDefaults.standard.set(newValue?.rawValue, forKey: "language"); cached = nil }
    }

    private static var cached: Lang?
    static var current: Lang {
        if let c = cached { return c }
        let l = chosen ?? Locale.preferredLanguages.lazy.compactMap(fromSystem).first ?? .en
        cached = l
        return l
    }

    // Matches the whole language subtag ("kab" is not "ka"). Scripts that are not translated fall back
    // to English: Traditional Chinese (zh-Hant, TW, HK, MO), Cyrillic Uzbek and Azerbaijani.
    private static func fromSystem(_ id: String) -> Lang? {
        let parts = id.split(whereSeparator: { $0 == "-" || $0 == "_" }).map(String.init)
        guard let code = parts.first, let lang = Lang(rawValue: code.lowercased()) else { return nil }
        let rest = Set(parts.dropFirst())
        if lang == .zh, !rest.isDisjoint(with: ["Hant", "TW", "HK", "MO"]) { return nil }
        if lang == .uz || lang == .az, rest.contains("Cyrl") { return nil }
        return lang
    }
}

